// Builds src/js/data/strokes.js from KanjiVG (CC BY-SA 3.0, https://kanjivg.tagaini.net).
// Usage: node tools/build-strokes.mjs [dirWithCachedSvgs]
// Without a directory, the SVGs are fetched from the KanjiVG GitHub repository.
import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = process.argv[2];
const FIRST = 0x3041, LAST = 0x3094; // ぁ .. ゔ

async function load(hex) {
  if (cacheDir) return readFile(join(cacheDir, `${hex}.svg`), "utf8");
  const res = await fetch(`https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/${hex}.svg`);
  if (!res.ok) throw new Error(`${hex}: HTTP ${res.status}`);
  return res.text();
}

const out = {};
for (let cp = FIRST; cp <= LAST; cp++) {
  const hex = cp.toString(16).padStart(5, "0");
  const svg = await load(hex);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${hex}: no strokes`);
  out[String.fromCodePoint(cp)] = paths;
}

const body = Object.entries(out)
  .map(([ch, paths]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(paths)}`)
  .join(",\n");

await writeFile(
  join(root, "src/js/data/strokes.js"),
  `/* Stroke data derived from KanjiVG (https://kanjivg.tagaini.net)
 * Copyright (C) 2009-2011 Ulrich Apel. Licensed CC BY-SA 3.0
 * (https://creativecommons.org/licenses/by-sa/3.0/). This file is distributed
 * under the same license. Generated by tools/build-strokes.mjs; do not edit.
 * Coordinates use KanjiVG's 109x109 box; strokes are listed in writing order. */
window.NH = window.NH || {};
NH.STROKES = {
${body}
};
`
);
console.log(`Wrote ${Object.keys(out).length} characters.`);
