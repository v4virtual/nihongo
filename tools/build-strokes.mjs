// Without a directory, the SVGs are fetched from the KanjiVG GitHub repository.
import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = process.argv[2];
// Hiragana ぁ..ゔ, katakana ァ..ヴ and the long-vowel mark ー.
const RANGES = [[0x3041, 0x3094], [0x30a1, 0x30f4], [0x30fc, 0x30fc]];
// The 80 kanji of JLPT N5 (the classic list), in the order kanji.js teaches them.
const KANJI = "一二三四五六七八九十百千万円日月火水木金土年時午前後今毎半間人子女男父母友先生名上下中左右外東西南北山川天気雨大小長高白本学校語電車国何見行来出入休食飲書読話聞";
// The clinic & hospital pack: reception, departments, symptoms, signs and parking.
const CLINIC = "病院医患者科内歯眼耳鼻皮膚児薬局師看護受付予約番号待合室初再診察券保険証会計様体熱痛血液温検査急救口非常階化粧禁煙注意危性示必面台乗倒遊等決願問当館京都府駐場利用方分料処理庫移動提請求";
// More everyday kanji (nature, things), then the stations & trains and shops & offices sets.
const MORE = "花海空石森林草風雪光星春夏秋冬犬猫鳥魚虫牛馬島池晴雲竹田葉物家茶米肉酒紙服傘箱皿机窓門手足目糸玉写真絵画音" +
  "駅線路鉄道地発着両次終始切符改札精算定期指席自由優快速各停普通特止降換段側戸開閉押" +
  "店売買品割引税込安値額新無員客営業準備銀現払預郵便送荷役所届類申記印明市区町村住";
// Restaurants & food.
const FOOD = "丼麺寿司刺身餃鍋豆腐卵菓飯野菜果焼揚唐煮汁味噌辛甘塩油冷氷文杯箸喫個盛放題別持帰";

async function load(hex) {
  if (cacheDir) return readFile(join(cacheDir, `${hex}.svg`), "utf8");
  const res = await fetch(`https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/${hex}.svg`);
  if (!res.ok) throw new Error(`${hex}: HTTP ${res.status}`);
  return res.text();
}

/* Walks the stroke groups: returns the strokes and the kanji's top-level
 * parts, e.g. 休 → 亻 (strokes 0, 1) + 木 (2–5). */
function parse(svg) {
  const body = svg.slice(svg.indexOf("kvg:StrokePaths_"), svg.indexOf("kvg:StrokeNumbers_"));
  const paths = [], types = [], parts = [], stack = [];
  for (const m of body.matchAll(/<g\b([^>]*)>|<\/g>|<path\b([^>]*?)\/?>/g)) {
    if (m[0].startsWith("</g")) {
      const g = stack.pop();
      if (stack.length !== 1 || !g.el || paths.length <= g.from) continue;
      const strokes = Array.from({ length: paths.length - g.from }, (_, i) => g.from + i);
      // A part split around others (囗 in 国, 二 in 五) is one part with a gap.
      const same = g.part && parts.find((q) => q.el === g.el && q.split);
      if (same) same.strokes.push(...strokes);
      else parts.push({ el: g.el, strokes, ...(g.pos && { pos: g.pos }), ...(g.radical && { radical: true }), ...(g.part && { split: true }) });
    } else if (m[0].startsWith("<g")) {
      const a = (k) => (m[1].match(new RegExp(`kvg:${k}="([^"]+)"`)) || [])[1];
      stack.push({ el: a("element"), pos: a("position"), radical: !!a("radical"), part: a("part"), from: paths.length });
    } else {
      paths.push(m[2].match(/\sd="([^"]+)"/)[1]);
      types.push((m[2].match(/kvg:type="([^"]+)"/) || [])[1] || "");
    }
  }
  return { paths, types, parts: parts.map(({ split, ...q }) => q) };
}

const out = {}, parts = {}, types = {};
const cps = [...RANGES.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i)), ...[...KANJI, ...CLINIC, ...MORE, ...FOOD].map((c) => c.codePointAt(0))];
for (const cp of cps) {
  const hex = cp.toString(16).padStart(5, "0");
  const { paths, types: t, parts: p } = parse(await load(hex));
  if (!paths.length) throw new Error(`${hex}: no strokes`);
  const ch = String.fromCodePoint(cp);
  out[ch] = paths;
  if (p.length > 1) parts[ch] = p;
  if (t.some(Boolean)) types[ch] = t;
}

const body = Object.entries(out)
  .map(([ch, paths]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(paths)}`)
  .join(",\n");

await writeFile(
  join(root, "src/js/data/strokes.js"),
  `/* Stroke data derived from KanjiVG (https://kanjivg.tagaini.net)
 * Copyright (C) 2009-2011 Ulrich Apel. Licensed CC BY-SA 3.0
 * (https://creativecommons.org/licenses/by-sa/3.0/). This file is distributed
 * under the same license. Generated by tools/build-strokes.mjs; do not edit.
 * Coordinates use KanjiVG's 109x109 box; strokes are listed in writing order. */
window.NH = window.NH || {};
NH.STROKES = {
${body}
};
// KanjiVG's stroke type per stroke (kanji only; kana have none), e.g. ㇒ a sweep, ㇚ a hook.
NH.STROKE_TYPES = {
${Object.entries(types).map(([ch, t]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(t)}`).join(",\n")}
};
// Top-level parts of each kanji that has more than one: the element and its stroke indexes.
NH.PARTS = {
${Object.entries(parts).map(([ch, p]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(p)}`).join(",\n")}
};
`
);
console.log(`Wrote ${Object.keys(out).length} characters, ${Object.keys(parts).length} with parts.`);
